// TransPerfect Modular System — taxonomy seed
// Derived from: Master Template Framework v0.2 + Master Wireframe Atlas v0.1.
// This is the source of truth until Lovable Cloud is enabled and these move to
// database tables. Shape mirrors the planned schema so migration is a copy.

export type BrandRole = "corporate" | "subcompany" | "division" | "product" | "cobrand";

export type BrandLogoLockup = {
  // Text-based lockup used until real logo assets are uploaded. `mark` is the
  // short glyph (1–4 chars), `wordmark` is the full name.
  mark: string;
  wordmark: string;
  // Optional secondary line rendered beneath the wordmark (division tagline).
  divisionLine?: string;
};

export type BrandContentScope = {
  industries: string[]; // e.g. "Life Sciences", "Legal", "Financial Services"
  serviceLines: string[]; // e.g. "Regulatory translation", "eDiscovery"
  caseStudyTags: string[]; // filters for case study modules
  preferredArchetypes: string[]; // narrative archetype ids that suit this brand
  restrictedFamilyIds?: string[]; // MF ids that are off-limits for this brand
  preferredVariantIds?: string[]; // MV ids the assembler should reach for first
};

export type BrandMode = {
  id: string;
  name: string;
  description: string;
  tokens: { primary: string; accent: string; surface: string; ink: string };
  // Enrichment layer — resolved from brand-profiles.ts at load time.
  role?: BrandRole;
  parentId?: string;
  logo?: BrandLogoLockup;
  contentScope?: BrandContentScope;
};

export type SectionFramework = {
  id: string; // SF-XX
  name: string;
  purpose: string;
  permittedFamilyIds: string[]; // MF-XX
};

export type ModuleFamily = {
  id: string; // MF-XX
  name: string;
  reviewLevel: "light" | "standard" | "strict";
  description: string;
};

export type LayoutFramework = {
  id: string; // LF-XX
  name: string;
  description: string;
  // Zones are declarative — the renderer maps zone names to grid regions.
  zones: string[];
};

export type ModuleVariant = {
  id: string; // MV-XX
  familyId: string;
  name: string;
  description: string;
  permittedLayoutIds: string[];
  capacity: {
    items?: { min: number; max: number };
    titleChars?: number;
    bodyChars?: number;
  };
  fallbackVariantId?: string;
  editableFields: string[];
  lockedFields: string[];
  // Optional iconography contract — see src/lib/iconography.ts. When omitted,
  // the renderer falls back to a "leading / md / soft-tile / accent" default
  // for list-like modules and "none" for pure-text modules.
  iconography?: {
    placement: import("./iconography").IconPlacement;
    size?: import("./iconography").IconSizeToken;
    treatment?: import("./iconography").IconTreatment;
    emphasis?: import("./iconography").IconEmphasis;
    a11yRole?: import("./iconography").IconA11yRole;
  };
};

export type NarrativeArchetype = {
  id: string;
  name: string;
  description: string;
  sectionRecipe: string[]; // ordered SF ids
};

